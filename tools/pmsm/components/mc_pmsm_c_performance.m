function performance=mc_pmsm_c_performance(configuration,operatingPoint,geometry,winding,mass,losses)
c=configuration; op=operatingPoint; P=op.power_W; s=op.electricMode;
if s==1, Pm=P+losses.total; eta=P/Pm; E=op.voltage_phase+op.current_A/c.a*winding.resistance_per_phase;
else, Pm=P-losses.total; eta=Pm/P; E=op.voltage_phase-op.current_A/c.a*winding.resistance_per_phase; end
performance=struct('rated_speed',op.speed_rpm,'speed',op.speed_rpm,'frequency',op.frequency_Hz,...
    'power',s*P,'mechanical_power',s*Pm,'efficiency',eta,'voltage',op.voltage_phase,...
    'electro_potential',E,'current',op.current_A,'current_density',c.A_s,...
    'torque_density',(P/op.omega)/(pi*(geometry.stator_OD/2000)^2*(geometry.core_length/1000)),...
    'power_density',P/1000/mass.total);
end
