function design_result = mc_pmsm_ind_PMSM_design( ...
    pmsm_input,electric_power_kW,rated_speed_rpm)
% PMSM设计
% 输入与额定工况处理
% 主尺寸计算
% 定子槽形与绕组设计
% 转子与磁钢设计
% 损耗与效率计算
% 质量与冷却结构计算
% 组装最终设计结果

%% 基础工况处理
operating = mc_pmsm_ind_prepare_design_operating( ...
    pmsm_input,electric_power_kW,rated_speed_rpm);

%% 1. 主要尺寸计算（D2L法）
[stator_inner_diameter_m,...
    stator_outer_diameter_m, ...
    core_length_m,...
    slot_count,...
    conductors_per_slot, ...
    electric_loading_A_per_m,...
    pmsm_input] = ...
    mc_pmsm_ind_calculate_main_dimensions( ...
        pmsm_input,operating);

%% 2. 定子槽形与绕组设计
[slot_params,...
    winding_params,...
    stator_outer_diameter_m,... 
    operating] = ...
    mc_pmsm_ind_calculate_stator_winding_design( ...
        pmsm_input,...
        stator_inner_diameter_m,stator_outer_diameter_m, ...
        core_length_m,slot_count,conductors_per_slot, ...
        operating,...
        electric_loading_A_per_m);

%% 3. 转子与磁钢设计
[rotor_outer_diameter_m,...
    rotor_inner_diameter_m, ...
    air_gap_m,...
    mag_params] = ...
    mc_pmsm_ind_calculate_rotor_magnet_design( ...
        pmsm_input,... 
        stator_inner_diameter_m,... 
        core_length_m, ...
        slot_params,... 
        operating);

%% 4. 质量与冷却结构计算
[mass_params,geometry] = mc_pmsm_ind_calculate_motor_mass( ...
    pmsm_input, operating, ...
    stator_inner_diameter_m, stator_outer_diameter_m, ...
    rotor_outer_diameter_m, rotor_inner_diameter_m, ...
    core_length_m, slot_count, slot_params,...
    winding_params, mag_params,air_gap_m);

%% 5. 损耗与效率计算
[losses,mag_params] = mc_pmsm_ind_calculate_total_losses( ...
    pmsm_input,operating,geometry, ...
    slot_params,mag_params, mass_params);

performance = mc_pmsm_ind_calculate_design_performance( ...
    operating,losses.total,geometry,mass_params);

%% 组装最终输出
design_result = mc_pmsm_ind_assemble_design_result( ...
    pmsm_input,geometry,mass_params,slot_params,mag_params, ...
    winding_params,operating,performance,losses);
end
