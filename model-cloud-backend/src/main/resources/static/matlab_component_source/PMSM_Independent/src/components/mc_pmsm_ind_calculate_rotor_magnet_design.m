function [rotor_outer_diameter_m,rotor_inner_diameter_m, ...
    air_gap_m,mag_params] = ...
    mc_pmsm_ind_calculate_rotor_magnet_design( ...
        pmsm_input,stator_inner_diameter_m,core_length_m, ...
        slot_params,operating)
% 转子与永磁体设计
% 选择磁钢材料，计算磁钢厚度、转子内外径及磁钢几何参数。

%% 从输入结构体获取本模块参数
air_gap_m = pmsm_input.h_airgap/1000;
pole_arc_ratio = pmsm_input.arc_factor;
carter_factor = pmsm_input.carter_factor;
equivalent_airgap_flux_density_T = pmsm_input.B_g;
pole_region_airgap_flux_density_T = ...
    equivalent_airgap_flux_density_T/pole_arc_ratio;
pole_pairs = pmsm_input.pole_pairs;
X_rotor = pmsm_input.X_rotor;
material_data = pmsm_input.material.data;
rated_speed_rpm = operating.speed;
%% 根据转速选择磁钢材料
if rated_speed_rpm > 5000
magnet_type = 'SmCo';
else
    magnet_type = 'NdFeB';
end

%% 获取磁钢材料参数
remanence_T = mc_pmsm_ind_get_prop(material_data,magnet_type,'B_r');
coercivity_kA_per_m = mc_pmsm_ind_get_prop(material_data,magnet_type,'H_cj');

%% 计算永磁体厚度
max_magnet_thickness_m = stator_inner_diameter_m/2-1e-3;
magnet_thickness_m = mc_pmsm_ind_calculate_pm_thickness( ...
    stator_inner_diameter_m,core_length_m,air_gap_m, ...
    pole_region_airgap_flux_density_T, ...
    remanence_T,coercivity_kA_per_m,carter_factor, ...
    pole_pairs,pole_arc_ratio, ...
    slot_params.opening_width/1000, ...
    slot_params.opening_height/1000);

%% 磁钢厚度几何限制
if magnet_thickness_m > max_magnet_thickness_m
    air_gap_m = air_gap_m ...
        * max_magnet_thickness_m/magnet_thickness_m;
    magnet_thickness_m = max_magnet_thickness_m;
end

%% 转子内外径计算
rotor_outer_diameter_m = stator_inner_diameter_m-2*air_gap_m;
rotor_inner_diameter_m = rotor_outer_diameter_m*X_rotor;

%% 组装磁钢几何参数
mag_params = struct( ...
    'magnet_type', magnet_type, ...
    'outer_diameter', 1000*rotor_outer_diameter_m, ...
    'pole_pairs', pole_pairs, ...
    'volume', core_length_m*pi ...
        *((rotor_outer_diameter_m/2)^2 ...
        - (rotor_outer_diameter_m/2-magnet_thickness_m)^2) ...
        * pole_arc_ratio, ...
    'height', 1000*magnet_thickness_m, ...
    'theta', pole_arc_ratio*360/2/pole_pairs, ...
    'segments', 1, ...
    'resistivity', -1, ...
    'loss_density', -1);
end
