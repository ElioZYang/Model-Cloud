function offdesign_result = mc_pmsm_ind_PMSM_off_design( ...
    design_result, electric_power_kW, operating_speed_rpm)
% PMSM非设计点性能计算
% 输入：
%   design_result - 设计点输出的完整结构体
%   electric_power_kW - 非设计点电功率 [kW]
%   operating_speed_rpm - 非设计点转速 [r/min]
% 输出：
%   offdesign_result - 非设计点参数结构体（与设计点结构体同构）
%% 继承设计点固定参数并更新当前工况
operation_mode = sign(electric_power_kW);
electric_power_W = abs(electric_power_kW) * 1000; % 功率单位转换为 W

%% 从设计点结果结构体提取参数
input_params = design_result.input;
geometry   = design_result.geometry;
winding    = design_result.winding;
mass       = design_result.mass;
% materials = design_result.materials;
thermal    = design_result.thermal;
slot       = design_result.slot;
mag_params = design_result.magnet;
design_performance = design_result.performance;
% 温度变量
temp_variables = thermal.temp_variables;
temp_values    = thermal.temp_values;
iron_temperature_C = temp_values(strcmpi(temp_variables,'temp_Fe'));
copper_temperature_C = temp_values(strcmpi(temp_variables,'temp_Cu'));

%% 非设计点工况下的基础计算
phase_count = input_params.N_phase;
electrical_frequency_Hz = ...
    winding.pole_pairs*operating_speed_rpm/60;
rated_speed_rpm = design_performance.rated_speed;

%% 基于反电动势和电阻压降的电压、电流计算
% 当前模型假设磁链不变，反电动势随转速线性变化；尚未实现dq轴弱磁控制。

% 温度修正后的铜电阻率
copper_resistivity_operating = input_params.rho_Cu ...
    * (1+input_params.alpha_Cu*(copper_temperature_C-20));
% 单位长度交流电阻
ac_resistance_per_m = mc_pmsm_ind_calculate_copper_resistance(...
    winding.wire_dia,electrical_frequency_Hz, ...
    copper_resistivity_operating, ...
    winding.conductors_per_slot, ...
    winding.wire_area);

conductor_length_per_phase = winding.conductor_length_per_phase;
phase_resistance_ohm = ac_resistance_per_m*conductor_length_per_phase;
phase_emf_V = design_performance.electro_potential ...
    * (operating_speed_rpm/rated_speed_rpm); % 额定电动势

switch operation_mode
    case 0
        phase_current_A = 0;
        phase_voltage_V = phase_emf_V;
    case 1
        phase_current_A = (phase_emf_V ...
            - sqrt(phase_emf_V^2 ...
            - 4*electric_power_W*(phase_resistance_ohm/input_params.a) ...
            /phase_count/input_params.cos_phi)) ...
            /(2*(phase_resistance_ohm/input_params.a));
        phase_voltage_V = phase_emf_V ...
            - phase_current_A*phase_resistance_ohm;
    case -1
        phase_current_A = (-phase_emf_V ...
            + sqrt(phase_emf_V^2 ...
            + 4*electric_power_W*(phase_resistance_ohm/input_params.a) ...
            /phase_count/input_params.cos_phi)) ...
            /(2*(phase_resistance_ohm/input_params.a));
        phase_voltage_V = phase_emf_V ...
            + phase_current_A*phase_resistance_ohm;
end

%% 组装非设计点工况参数
% 性能参数更新
mechanical_angular_speed = operating_speed_rpm*pi/30; % 机械角速度 [rad/s]
wire_area_mm2 = winding.wire_area*1e6;
current_density_A_per_mm2 = ...
    (phase_current_A/input_params.a)/wire_area_mm2;

electric_loading_A_per_m = winding.conductors_per_slot ...
    *phase_current_A ...
    *geometry.slot_number...
    /(input_params.a*pi*geometry.stator_ID/1000);

operating = struct( ...
    'cal_mode',            operation_mode, ...
    'electric_power',      electric_power_W, ...
    'speed',               operating_speed_rpm, ...
    'omega',               mechanical_angular_speed, ...
    'frequency',           electrical_frequency_Hz, ...
    'phase_voltage',       phase_voltage_V, ...
    'phase_current',       phase_current_A, ...
    'phase_resistance',    phase_resistance_ohm, ...
    'electro_potential',   phase_emf_V, ...
    'electric_loading',    electric_loading_A_per_m, ...
    'current_density',     current_density_A_per_mm2, ...
    'airgap_flux_density', input_params.B_g, ...
    'temp_Cu',             copper_temperature_C, ...
    'temp_Fe',             iron_temperature_C);

%% 非设计点损耗计算
[losses,mag_params] = mc_pmsm_ind_calculate_total_losses(...
    input_params,operating,geometry, ...
    slot,mag_params,mass);
total_loss_W = losses.total;


%% 效率计算

switch operation_mode
    case 0
        efficiency = 1;
        mechanical_power_W = 0;

    case 1
        mechanical_power_W = electric_power_W+total_loss_W;
        efficiency = electric_power_W/mechanical_power_W;

    case -1
        mechanical_power_W = electric_power_W-total_loss_W;
        efficiency = mechanical_power_W/electric_power_W;

end

%% 更新输出结构体的非设计点参数

performance_offdesign = struct(...
    'speed',               operating.speed, ...
    'frequency',           operating.frequency, ...
    'power',               operation_mode*electric_power_W, ...
    'mechanical_power',    operation_mode*mechanical_power_W, ...
    'efficiency',          efficiency, ...
    'voltage',             operating.phase_voltage, ...
    'electro_potential',   operating.electro_potential, ...
    'current',             operating.phase_current, ...
    'electric_loading',    operating.electric_loading, ...
    'current_density',     operating.current_density);

field_names = fieldnames(performance_offdesign);
offdesign_result = design_result;
for field_name = field_names'
    offdesign_result.performance.(field_name{1}) = ...
        performance_offdesign.(field_name{1});
end

% 保存当前工况及其损耗
offdesign_result.losses    = losses;
offdesign_result.operating = operating;
offdesign_result.magnet    = mag_params;
end
