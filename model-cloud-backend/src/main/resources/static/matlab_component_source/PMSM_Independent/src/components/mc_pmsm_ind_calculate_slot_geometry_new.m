%% 槽形计算子函数
function [slot,stator_outer_diameter_m] = mc_pmsm_ind_calculate_slot_geometry_new( ...
    stator_inner_diameter_m,stator_outer_diameter_m, ...
    minimum_slot_area_m2,slot_count,pole_pairs,stacking_factor, ...
    slot_fill_factor,tooth_width_ratio,yoke_height_ratio, ...
    airgap_flux_density_T,tooth_flux_density_T,yoke_flux_density_T)
    % 优化版槽形设计函数
    % 输入:
    %   stator_inner_diameter_m, stator_outer_diameter_m: 定子直径 [m]
    %   minimum_slot_area_m2: 所需最小槽面积 [m^2]
    %   slot_count: 定子槽数
    %   stacking_factor: 铁芯叠压系数
    %   airgap_flux_density_T: 磁极覆盖区气隙磁密 [T]
    %   tooth_flux_density_T, yoke_flux_density_T: 齿/轭部磁密 [T]
    % 输出:
    %   slot: 槽形参数结构体（长度为 mm，面积为 mm^2）
    %   stator_outer_diameter_m: 满足槽面积后的定子外径 [m]


    % 1. 计算基本几何量
    slot_pitch_m = pi*stator_inner_diameter_m/slot_count;

    % 3. 确定槽口宽度 (基于工艺和齿部磁密)
    slot_opening_width_m = .2*slot_pitch_m;
    slot_angle_rad = 2*pi/slot_count;
    slot_opening_height_m = slot_opening_width_m;
    
    % 4. 计算齿宽 (核心约束1: 齿部磁密)
    if tooth_width_ratio > 0
        tooth_width_m = tooth_width_ratio*slot_pitch_m;
        tooth_flux_density_T = airgap_flux_density_T*slot_pitch_m ...
            /(tooth_width_m*stacking_factor);
    else
        tooth_width_m = airgap_flux_density_T*slot_pitch_m ...
            /(tooth_flux_density_T*stacking_factor);
    end

    % 5. 计算所需轭部高度 (核心约束2: 轭部磁密)
    pole_pitch_m = pi*stator_inner_diameter_m/(2*pole_pairs);
    if yoke_height_ratio > 0
        yoke_height_m = yoke_height_ratio*stator_inner_diameter_m/2;
        yoke_flux_density_T = airgap_flux_density_T*pole_pitch_m ...
            /(2*yoke_height_m*stacking_factor);
    else
        yoke_height_m = airgap_flux_density_T*pole_pitch_m ...
            /(2*yoke_flux_density_T*stacking_factor);
    end

    % 防止槽面积不足
    quadratic_a = .5*slot_angle_rad;
    quadratic_b = slot_angle_rad ...
        *(stator_inner_diameter_m/2+slot_opening_height_m) ...
        - tooth_width_m;
    quadratic_c = -minimum_slot_area_m2;
    minimum_slot_body_depth_m = ...
        (-quadratic_b+sqrt(quadratic_b^2 ...
        - 4*quadratic_a*quadratic_c))/(2*quadratic_a);
    minimum_stator_outer_diameter_m = stator_inner_diameter_m ...
        + 2*(slot_opening_height_m+minimum_slot_body_depth_m ...
        + yoke_height_m);
    stator_outer_diameter_m = max( ...
        stator_outer_diameter_m,minimum_stator_outer_diameter_m);
    stator_radial_build_m = ...
        (stator_outer_diameter_m-stator_inner_diameter_m)/2;
    total_slot_depth_m = stator_radial_build_m-yoke_height_m;
    slot_body_depth_m = total_slot_depth_m-slot_opening_height_m;

    % 7. 定义槽身部分 (梯形)
    % 假设槽身高度 = 总槽深 - 槽口高度
    % 梯形槽底宽
    slot_bottom_width_m = ...
        pi*(stator_inner_diameter_m+2*total_slot_depth_m)/slot_count ...
        - tooth_width_m ...
        *(stator_inner_diameter_m+2*total_slot_depth_m) ...
        /(stator_inner_diameter_m+total_slot_depth_m);

    % 8. 计算槽净面积 (槽口矩形 + 槽身梯形)
    slot_opening_area_m2 = ...
        ((stator_inner_diameter_m/2+slot_opening_height_m)^2 ...
        - stator_inner_diameter_m^2/4) ...
        * slot_opening_width_m/stator_inner_diameter_m;
    slot_body_area_m2 = ...
        ((stator_inner_diameter_m/2+total_slot_depth_m)^2 ...
        - (stator_inner_diameter_m/2+slot_opening_height_m)^2) ...
        * slot_bottom_width_m ...
        /(stator_inner_diameter_m+2*total_slot_depth_m);
%     slot_fill=slot_fill_max*A_slot_req/A_slot_body;
    total_slot_area_m2 = slot_opening_area_m2+slot_body_area_m2;
    
    % 9. 组装输出
    slot = struct(...
        'opening_width',  slot_opening_width_m*1000, ...
        'opening_height', slot_opening_height_m*1000, ...
        'body_depth',     slot_body_depth_m*1000, ...
        'total_depth',    total_slot_depth_m*1000, ...
        'bottom_width',   slot_bottom_width_m*1000, ...
        'yoke_height',    yoke_height_m*1000, ...
        'area_body',      slot_body_area_m2*1e6, ...
        'area',           total_slot_area_m2*1e6, ...
        'tooth_width',    tooth_width_m*1000, ...
        'tooth_flux_density', tooth_flux_density_T, ...
        'yoke_flux_density', yoke_flux_density_T, ...
        'slot_fill',      slot_fill_factor, ...
        'slot_number',    slot_count);

%     valid = true;
%     fprintf('槽形设计成功。齿部磁密: %.2f T, 轭部高度: %.1f mm, 槽面积: %.1f mm²\n', ...
%             B_tooth, h_yoke_req*1000, A_slot*1e6);
end
