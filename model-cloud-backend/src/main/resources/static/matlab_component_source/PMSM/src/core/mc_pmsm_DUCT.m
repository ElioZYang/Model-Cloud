function[OUTPUT]=mc_pmsm_DUCT(INPUT)
OUTPUT=INPUT;
switch INPUT.mode
    case "design"
OUTPUT.P=INPUT.TPR*INPUT.P;
OUTPUT.T=INPUT.T+1000*INPUT.dH/INPUT.WA/(1+INPUT.FAR)/mc_pmsm_CPSH(INPUT.T,INPUT.FAR);
OUTPUT.WCOR=INPUT.WA*(1+INPUT.FAR)*(INPUT.T)^0.5/INPUT.P;
    case "offdesign"
DPR=1-INPUT.TPR;
WCOR=INPUT.WCOR;
OUTPUT.WCOR=INPUT.WA*(1+INPUT.FAR)*(INPUT.T)^0.5/INPUT.P;
TPR=1-DPR*(OUTPUT.WCOR/WCOR)^2;
OUTPUT.P=TPR*INPUT.P;
if INPUT.WA>0
OUTPUT.T=INPUT.T+1000*INPUT.dH/INPUT.WA/(1+INPUT.FAR)/mc_pmsm_CPSH(INPUT.T,INPUT.FAR);
else
OUTPUT.T=INPUT.T;
end
end
OUTPUT.dT=OUTPUT.T-INPUT.T;
OUTPUT.dP=OUTPUT.P-INPUT.P;
OUTPUT.WA=INPUT.WA*(1-INPUT.WA_extraction);
end