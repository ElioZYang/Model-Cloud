function design_result = assemble_design_result( ...
    pmsm_input,geometry,mass_params,slot_params,mag_params, ...
    winding_params,operating,performance,losses)
% 保持设计结果的公开字段和工况字段顺序，隐藏内部辅助量。
operating = rmfield(operating,'rated_torque');
operating = orderfields(operating, { ...
    'cal_mode','electric_power','speed','omega','frequency', ...
    'phase_voltage','phase_current','phase_resistance', ...
    'electro_potential','electric_loading','current_density', ...
    'airgap_flux_density','temp_Cu','temp_Fe'});
design_result = struct( ...
    'input',pmsm_input, ...
    'geometry',geometry, ...
    'mass',mass_params, ...
    'slot',slot_params, ...
    'magnet',mag_params, ...
    'winding',winding_params, ...
    'operating',operating, ...
    'performance',performance, ...
    'losses',losses, ...
    'thermal',pmsm_input.thermal);
end
