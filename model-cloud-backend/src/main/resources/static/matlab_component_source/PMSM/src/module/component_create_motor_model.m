function response = component_create_motor_model(request)
%COMPONENT_CREATE_MOTOR_MODEL 将PMSM设计结果封装为可复用电机模型。
%
% 输入：request.inputs.design_result
% 输出：response.outputs.motor_model

design_result = require_component_input(request, 'design_result', ...
    'PMSM:CreateMotorModel:MissingDesignResult', ...
    '电机模型组件缺少 request.inputs.design_result。');
require_business_fields(design_result, ...
    {'input', 'geometry', 'mass', 'slot', 'magnet', 'winding', ...
     'operating', 'performance', 'losses', 'thermal'}, ...
    'design_result', 'PMSM:CreateMotorModel:InvalidDesignResult');

motor_model = struct();
motor_model.meta = struct( ...
    'model_id', '', ...
    'model_name', 'PMSM Motor', ...
    'schema_version', '1.0', ...
    'source', 'design_workflow');
if isfield(design_result.input, 'configuration')
    motor_model.configuration = design_result.input.configuration;
else
    motor_model.configuration = struct( ...
        'source', 'default', 'templateVersion', '1.0');
end

motor_model.design = struct( ...
    'input', design_result.input, ...
    'geometry', design_result.geometry, ...
    'slot', design_result.slot, ...
    'magnet', design_result.magnet, ...
    'winding', design_result.winding, ...
    'mass', design_result.mass, ...
    'thermal', design_result.thermal);

motor_model.rated_condition = design_result.operating;
motor_model.baseline = struct( ...
    'losses', design_result.losses, ...
    'performance', design_result.performance);

response = struct();
response.outputs = struct('motor_model', motor_model);
end

function result = require_component_input(request, field_name, error_id, message)
if ~isstruct(request) || ~isfield(request, 'inputs') ...
        || ~isstruct(request.inputs) || ~isfield(request.inputs, field_name)
    error(error_id, message);
end
result = request.inputs.(field_name);
if ~isstruct(result)
    error(error_id, '%s 必须是结构体。', message);
end
end

function require_business_fields(value, fields, value_name, error_id)
for index = 1:numel(fields)
    if ~isfield(value, fields{index})
        error(error_id, '%s 缺少字段 %s。', value_name, fields{index});
    end
end
end
