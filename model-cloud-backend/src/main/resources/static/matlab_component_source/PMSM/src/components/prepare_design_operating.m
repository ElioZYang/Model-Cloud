function operating = prepare_design_operating( ...
    pmsm_input,electric_power_kW,rated_speed_rpm)
% 基础设计工况；功率为幅值，cal_mode 保留输入功率的方向。
electric_power_W = abs(electric_power_kW)*1000;
phase_voltage_V = pmsm_input.voltage_phase;
if phase_voltage_V < 0
    phase_voltage_V = pmsm_input.voltage_line/sqrt(3);
end
mechanical_angular_speed = rated_speed_rpm*pi/30;
temp_variables = pmsm_input.thermal.temp_variables;
temp_values = pmsm_input.thermal.temp_values;
operating = struct( ...
    'cal_mode', sign(electric_power_kW), ...
    'electric_power', electric_power_W, ...
    'speed', rated_speed_rpm, ...
    'omega', mechanical_angular_speed, ...
    'frequency', pmsm_input.pole_pairs*rated_speed_rpm/60, ...
    'phase_voltage', phase_voltage_V, ...
    'phase_current', electric_power_W ...
        /(pmsm_input.N_phase*phase_voltage_V*pmsm_input.cos_phi), ...
    'airgap_flux_density', pmsm_input.B_g, ...
    'temp_Cu', temp_values(strcmpi(temp_variables,'temp_Cu')), ...
    'temp_Fe', temp_values(strcmpi(temp_variables,'temp_Fe')), ...
    'rated_torque', electric_power_W/mechanical_angular_speed);
end
