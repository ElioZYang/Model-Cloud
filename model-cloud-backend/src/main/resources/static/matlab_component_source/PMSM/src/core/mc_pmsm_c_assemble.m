function motorModel=mc_pmsm_c_assemble(configuration,geometry,slot,winding,magnet,mass,losses,performance)
g=geometry;
geometry=struct('cgv_height',g.cgv_height,'cgv_length',g.cgv_length,'housing_OD',g.housing_OD,...
    'stator_OD',g.stator_OD,'stator_ID',g.stator_ID,'rotor_OD',g.rotor_OD,'rotor_ID',g.rotor_ID,...
    'core_length',g.core_length,'air_gap',g.air_gap,'slot_number',g.slot_number,'pole_pairs',g.pole_pairs);
motorModel=struct('input',configuration,'geometry',geometry,'mass',mass,'slot',slot,'magnet',magnet,...
    'winding',winding,'performance',performance,'losses',losses,'thermal',configuration.thermal);
end
