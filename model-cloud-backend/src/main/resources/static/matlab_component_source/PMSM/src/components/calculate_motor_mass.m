function [mass_params,geometry] = calculate_motor_mass( ...
    pmsm_input,... 
    operating, ...
    stator_inner_diameter_m,stator_outer_diameter_m, ...
    rotor_outer_diameter_m,rotor_inner_diameter_m, ...
    core_length_m,slot_count,slot_params, ...
    winding_params,mag_params,air_gap_m)
% 电机质量与冷却结构计算
% 计算定转子、绕组、磁钢、机壳、轴及冷却结构的质量。

%% 从输入结构体获取本模块参数
phase_count = pmsm_input.N_phase;
slot_fill = pmsm_input.slot_fill;
cooling = pmsm_input.cooling;
XC_cgv = pmsm_input.XC_cgv;
XH_cgv = pmsm_input.XH_cgv;
material_data = pmsm_input.material.data;
pole_pairs   = pmsm_input.pole_pairs;
electric_power_W = operating.electric_power;
%% 获取材料密度
rotor_density    = get_prop(material_data,'steel_shaft','density');
copper_density   = get_prop(material_data,'copper','density');
cavity_density   = get_prop(material_data,'cavity','density');
magnet_density   = get_prop(material_data,mag_params.magnet_type,'density');
aluminum_density = get_prop(material_data,'aluminum','density');

%% 定子铁芯质量
% 计算定子齿部和轭部质量
yoke_height_m = slot_params.yoke_height/1000;
yoke_volume_m3 = pi/4 ...
    *(stator_outer_diameter_m^2 ...
    - (stator_outer_diameter_m-2*yoke_height_m)^2)*core_length_m;
tooth_volume_m3 = pi/4 ...
    *(stator_outer_diameter_m^2-stator_inner_diameter_m^2) ...
    * core_length_m ...
    - slot_params.area/1e6*slot_count*core_length_m ...
    - yoke_volume_m3;

stator_density = get_prop(material_data,'steel','density');
stator_tooth_mass_kg = tooth_volume_m3*stator_density;
stator_yoke_mass_kg = yoke_volume_m3*stator_density;

stator_mass_kg = stator_tooth_mass_kg+stator_yoke_mass_kg;

%% 转子铁芯质量
rotor_core_volume_m3 = pi/4*rotor_outer_diameter_m^2 ...
    * core_length_m-mag_params.volume;
rotor_core_mass_kg = rotor_density*rotor_core_volume_m3;

%% 绕组和槽内填充材料质量
wire_area_m2 = winding_params.wire_area;
conductor_length_per_phase = winding_params.conductor_length_per_phase;
% 按配置表中的实际相数计算整机铜质量。
copper_mass_kg = copper_density*phase_count ...
    * conductor_length_per_phase*wire_area_m2;
cavity_mass_kg = cavity_density*slot_params.area/1e6 ...
    * core_length_m*slot_count*(1-slot_fill);

%% 永磁体质量
magnet_mass_kg = magnet_density*mag_params.volume;

%% 机壳质量
housing_thickness_m = 0.1*stator_outer_diameter_m;
housing_outer_diameter_m = stator_outer_diameter_m ...
    + 2*housing_thickness_m;
housing_volume_m3 = pi/4 ...
    *(housing_outer_diameter_m^2-stator_outer_diameter_m^2) ...
    *(core_length_m+0.05) ...
    + pi/4*housing_outer_diameter_m^2*2*housing_thickness_m;
housing_mass_kg = aluminum_density*housing_volume_m3;

%% 冷却结构质量
heat_exchanger_mass_kg = 0;
guide_vane_mass_kg = 0;
guide_vane_height_m = 0.5*XH_cgv*housing_outer_diameter_m;
guide_vane_length_m = XC_cgv*core_length_m;

switch cooling
    case {1,2}
        % 空气冷却或热管导叶冷却
        guide_vane_mass_kg = slot_count*guide_vane_height_m ...
            * guide_vane_length_m*0.06*guide_vane_length_m ...
            * aluminum_density;
    case 3
        % 水冷换热器经验质量
        heat_exchanger_mass_kg = 15*electric_power_W/1e5;
end

%% 轴质量
shaft_extension = 0.05;
shaft_volume_m3 = pi*(rotor_inner_diameter_m/2)^2 ...
    *(2*shaft_extension);
shaft_mass_kg = rotor_density*shaft_volume_m3;

%% 总质量
total_mass_kg = stator_mass_kg+rotor_core_mass_kg+copper_mass_kg ...
    + cavity_mass_kg+magnet_mass_kg+housing_mass_kg+shaft_mass_kg ...
    + guide_vane_mass_kg+heat_exchanger_mass_kg;

%% 组装质量参数
mass_params = struct( ...
    'stator_tooth', stator_tooth_mass_kg, ...
    'stator_yoke', stator_yoke_mass_kg, ...
    'rotor_core', rotor_core_mass_kg, ...
    'copper', copper_mass_kg, ...
    'cavity', cavity_mass_kg, ...
    'magnets', magnet_mass_kg, ...
    'housing', housing_mass_kg, ...
    'shaft', shaft_mass_kg, ...
    'cgv', guide_vane_mass_kg, ...
    'heat_exchanger', heat_exchanger_mass_kg, ...
    'total', total_mass_kg);

%% 组装几何参数（长度由 m 转换为 mm）
geometry = struct( ...
    'cgv_height',   guide_vane_height_m*1000, ...
    'cgv_length',   guide_vane_length_m*1000, ...
    'housing_OD',   housing_outer_diameter_m*1000, ...
    'stator_OD',    stator_outer_diameter_m*1000, ...
    'stator_ID',    stator_inner_diameter_m*1000, ...
    'rotor_OD',     rotor_outer_diameter_m*1000, ...
    'rotor_ID',     rotor_inner_diameter_m*1000, ...
    'core_length',  core_length_m*1000, ...
    'air_gap',      air_gap_m*1000, ...
    'slot_number',  slot_count, ...
    'pole_pairs',   pole_pairs);
end
