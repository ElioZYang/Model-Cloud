function windage_loss_W = calculate_windage_losses(...
    air_density_kg_per_m3,air_dynamic_viscosity_Pa_s, ...
    mechanical_angular_speed_rad_per_s, ...
    rotor_outer_diameter_m,rotor_inner_diameter_m, ...
    core_length_m,air_gap_m)
    airgap_reynolds = air_density_kg_per_m3 ...
        * mechanical_angular_speed_rad_per_s ...
        * rotor_outer_diameter_m*air_gap_m ...
        /(2*air_dynamic_viscosity_Pa_s);
    if airgap_reynolds < 64
         airgap_friction_coefficient = ...
             10*(2*air_gap_m/rotor_outer_diameter_m)^.3 ...
             /airgap_reynolds;
    elseif airgap_reynolds < 500
         airgap_friction_coefficient = ...
             2*(2*air_gap_m/rotor_outer_diameter_m)^.3 ...
             /airgap_reynolds^.6;
    elseif airgap_reynolds < 1e4
         airgap_friction_coefficient = ...
             1.03*(2*air_gap_m/rotor_outer_diameter_m)^.3 ...
             /airgap_reynolds^.5;
    else
         airgap_friction_coefficient = ...
             .065*(2*air_gap_m/rotor_outer_diameter_m)^.3 ...
             /airgap_reynolds^.2;
    end

    airgap_windage_loss_W = ...
        1/32*airgap_friction_coefficient*pi*air_density_kg_per_m3 ...
        * mechanical_angular_speed_rad_per_s^3 ...
        * rotor_outer_diameter_m^4*core_length_m;
    tip_reynolds = air_density_kg_per_m3 ...
        * mechanical_angular_speed_rad_per_s ...
        * rotor_outer_diameter_m^2/(4*air_dynamic_viscosity_Pa_s);
    if tip_reynolds < 3e5
        tip_friction_coefficient = 3.87/tip_reynolds^.5;
    else
        tip_friction_coefficient = .146/tip_reynolds^.2;
    end

    endface_windage_loss_W = ...
        1/64*tip_friction_coefficient*air_density_kg_per_m3 ...
        * mechanical_angular_speed_rad_per_s^3 ...
        * (rotor_outer_diameter_m^5-rotor_inner_diameter_m^5);
    windage_loss_W = endface_windage_loss_W + airgap_windage_loss_W;
end
