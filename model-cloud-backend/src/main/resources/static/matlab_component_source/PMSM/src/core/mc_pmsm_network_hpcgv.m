if exist('Rt_yoke','var') && ~isa(Rt_yoke,'function_handle'), state.Rt_yoke=Rt_yoke; end
if exist('Rx_fe','var') && ~isa(Rx_fe,'function_handle'), state.Rx_fe=Rx_fe; end
