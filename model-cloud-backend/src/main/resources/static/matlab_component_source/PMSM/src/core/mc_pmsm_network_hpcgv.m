if isfield(state,'Rr_yoke3'), Rr_yoke3=state.Rr_yoke3; end
if isfield(state,'Rro'), Rro=state.Rro; end
if isfield(state,'Rt_winding'), Rt_winding=state.Rt_winding; end
if isfield(state,'Rt_yoke'), Rt_yoke=state.Rt_yoke; end
