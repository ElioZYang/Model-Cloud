if isfield(state,'Rr_winding1'), Rr_winding1=state.Rr_winding1; end
if isfield(state,'Rr_winding2'), Rr_winding2=state.Rr_winding2; end
if isfield(state,'Rr_yoke1'), Rr_yoke1=state.Rr_yoke1; end
