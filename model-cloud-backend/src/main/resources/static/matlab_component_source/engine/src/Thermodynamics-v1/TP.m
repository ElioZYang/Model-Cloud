function [ P ] = TP( T,S,FAR)
%根据温度、熵、油气比计算气体总压力
%Total Pressure
%输入参数
% T     温度
% S     熵
% FAR   油气比
%输出参数
% P     压力
A=[1.92496823e-01,-9.27663822e-05, 1.061415673e-07,...
    -1.30594763e-11,-3.97026034e-14, 2.880297413e-17,...
    -8.23479508e-21, 8.84704904e-25, 2.50200510e-01];
B=[6.91728236e-01, 2.20655340e-03,-2.23104796e-06,...
    1.93791108e-09,-1.10358917e-12, 3.85959872e-16,...
    -7.55959704e-20, 6.35647856e-24, 7.38166380e-02];
sa=0;
sf=0;
for i=1:8
    sa=sa+A(i)*(T^(i-1));
    sf=sf+B(i)*(T^(i-1));
end
sa=sa+A(9)*log(T);
sf=sf+B(9)*log(T);
f=(sa + FAR*sf)/(1. + FAR)*427.*9.80665;
%湿度修正
P=101325.2*exp((f - S)/GC(FAR));
end

