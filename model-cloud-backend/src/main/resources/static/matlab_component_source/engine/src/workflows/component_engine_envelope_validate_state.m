function component_engine_envelope_validate_state(scan_state)
%COMPONENT_ENGINE_ENVELOPE_VALIDATE_STATE Validate a scan_state chain value.
if ~isstruct(scan_state) || ~isfield(scan_state, 'DP') || ...
        ~isfield(scan_state, 'OP') || ~isfield(scan_state, 'X0') || ...
        ~isfield(scan_state, 'DX') || ~isfield(scan_state, 'MAP') || ...
        ~isfield(scan_state, 'THRUST_ARRAY') || ~isfield(scan_state, 'TIT_ARRAY') || ...
        ~isfield(scan_state, 'COMP_WP') || ~isfield(scan_state, 'TURB_WP') || ...
        ~isfield(scan_state, 'MOTOR_WP')
    error('engine:InvalidScanState', 'scan_state is incomplete.');
end
end
