function PROPERTY=PRO(T,obj,fun)
% obj=1，比焓
% obj=2，定压比热容
% obj=3，熵函数
% fun=1，空气
% fun=2，ceta函数
% fun=3，水蒸气
t=T/1000;
A=[-301836.74	1048965.2	-232840.57	452884.31	-313084.77	113413.62	-21298.087	1636.36	0	8055.8643;
-111525.75	-310202.06	2996119.7	-2793478.8	1874640.7	-734995.97	150626.02	-12510.984	0	-1780.0633;
-13988826.67	1885047.278	242390.45	588607.5556	-305290.5056	83051.83333	12651.25278	993.0543333	-29.57558111	12841.09333
];
    a1=A(fun,(1:9));
    a1=flip(a1);
    a2=(1:8).*a1(2:9)./1000;
    a2=flip(a2);
    a3=(2:8)./(1:7).*a1(3:9)./1000;
    phi0=A(fun,10);
    a3=[phi0,a3];
    a3=flip(a3);
    if obj==1
        PROPERTY=polyval(a1,t);
    elseif obj==2
        PROPERTY=polyval(a2,t);
    else
        PROPERTY=polyval(a3,t)+a1(2)*log(t);
    end