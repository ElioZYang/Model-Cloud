function [OUTPUT] = TURBINE(INPUT)
%根据压比，效率，进口温度与压力考虑变比热影响计算压缩过程
%膨胀过程也可用此计算，但是压比及效率应输入为膨胀比和涡轮效率的倒数
%Total Paremeters of Compression 
%输入参数
% PR    压缩比
% ES    等熵效率
% T1    进口温度
% P1    进口压力
% FAR   油气比
%输出参数
% T2    出口温度
% P2    出口压力
switch INPUT.mode
    case 'design'
OUTPUT=INPUT;
H1=SE(INPUT.T,INPUT.FAR);
S1=E(INPUT.T,INPUT.P,INPUT.FAR,INPUT.D);
OUTPUT.P=INPUT.P/INPUT.PR;
%计算出口总温初值
T2S=INPUT.T*INPUT.PR^-0.28572;
%设定熵差限
fun=@(T2S) E(T2S,OUTPUT.P,OUTPUT.FAR,OUTPUT.D)/S1-1;
T2S=fzero(fun,T2S);
H2S=SE(T2S,OUTPUT.FAR);
H2=H1+(H2S-H1)*OUTPUT.EFF;
T2=TT(H2,OUTPUT.FAR);
OUTPUT.T=T2;
OUTPUT.PWT=(H2-H1)*OUTPUT.WA*(1+OUTPUT.FAR)/1000;
OUTPUT.WGC=OUTPUT.WA*(1+OUTPUT.FAR)*sqrt(INPUT.T)/INPUT.P;
OUTPUT.NT0=OUTPUT.N/sqrt(INPUT.T);
    case 'offdesign'
OUTPUT=INPUT;
R=INPUT.R;
MAP=INPUT.MAP;
NCOR=INPUT.N/sqrt(INPUT.T);
NCOR_ref=NCOR/INPUT.NT0;
O=MAPPING('turb',MAP,NCOR_ref,R);
OUTPUT.overload=O.overload;
OUTPUT.NCOR=NCOR;
OUTPUT.NCOR_ref=NCOR_ref;
OUTPUT.WGC_ref=O.WGC;
OUTPUT.WGC=O.WGC*INPUT.WGC0;
W1=OUTPUT.WGC*INPUT.P/sqrt(INPUT.T);
OUTPUT.DW=W1/INPUT.WA/(1+INPUT.FAR)-1;
OUTPUT.WA=W1/(1+INPUT.FAR);
OUTPUT.PR_ref=O.PR;
OUTPUT.PR=O.PR*(INPUT.PRT0-1)+1;
% OUTPUT.PR=O.PR*INPUT.PRT0;
OUTPUT.EFF=O.EFF*INPUT.EFFT0;
OUTPUT.EFF=max(0.1,OUTPUT.EFF);
OUTPUT.PR=max(0.5,OUTPUT.PR);
% offdesign point calculate
H1=SE(INPUT.T,INPUT.FAR);
S1=E(INPUT.T,INPUT.P,INPUT.FAR,INPUT.D);
OUTPUT.P=INPUT.P/OUTPUT.PR;
%计算出口总温初值
T2S=OUTPUT.T*OUTPUT.PR^-0.28572;
fun=@(T2S) E(T2S,OUTPUT.P,OUTPUT.FAR,OUTPUT.D)/S1-1;
T2S=fzero(fun,T2S);
H2S=SE(T2S,OUTPUT.FAR);
H2=H1+(H2S-H1)*OUTPUT.EFF;
T2=TT(H2,OUTPUT.FAR);
OUTPUT.T=T2;
OUTPUT.PWT=(H2-H1)*OUTPUT.WA*(1+OUTPUT.FAR)/1000;
end
end

