function report = component_engine_entry_tests()
%COMPONENT_ENGINE_ENTRY_TESTS Check the three-stage engine entry contract.
% This test intentionally checks raw DP fields and orientation.  It does not
% add a physical validity policy to the production entry points.
configs = {'ducted fan','turboshaft','mixed turbofan'};
report = repmat(struct('configuration','', 'passed',false, 'field_count',0), ...
    1, numel(configs));
for k = 1:numel(configs)
    DP = component_engine_initialize_configuration(configs{k}, 60, 0, 3000);
    assert(isfield(DP, 'F') && isfield(DP, 'SHAFT') && ...
        isfield(DP, 'EXT') && isfield(DP, 'WA_extraction'));
    original_f = DP.F;
    original_shaft = DP.SHAFT;
    original_ext = DP.EXT;
    original_extraction = DP.WA_extraction;
    DP = component_engine_apply_design_conditions(DP, 0, 0, ...
        1000 * ones(DP.NS, 1));
    assert(isequal(DP.F, original_f));
    assert(isequal(DP.SHAFT, original_shaft));
    assert(isequal(DP.EXT, original_ext));
    assert(isequal(DP.WA_extraction, original_extraction));
    [DP, XD] = component_engine_solve_design_point(DP); %#ok<ASGLU>
    assert(isfield(DP, 'YD'));
    report(k).configuration = configs{k};
    report(k).passed = true;
    report(k).field_count = numel(fieldnames(DP));
end

% Explicit shape/type descriptors must restore the JSON row orientation.
assembly_json = ['{"type":{"value":"custom","type":"string"},' ...
    '"NS":{"value":1,"type":"double","shape":[1,1]},' ...
    '"NW":{"value":0,"type":"double","shape":[1,1]},' ...
    '"F":{"value":["inlet","lpc","nozzle"],"type":"string","shape":[1,3]},' ...
    '"TPR":{"value":[-1,1,0.97],"type":"double","shape":[1,3]},' ...
    '"EFFC":{"value":0.87,"type":"double","shape":[1,1]},' ...
    '"PRC":{"value":1.1,"type":"double","shape":[1,1]},' ...
    '"EFFT":{"value":1,"type":"double","shape":[1,1]},' ...
    '"PRT":{"value":0,"type":"double","shape":[1,1]},' ...
    '"EB":{"value":1,"type":"double","shape":[1,1]},' ...
    '"HU":{"value":1,"type":"double","shape":[1,1]},' ...
    '"TO":{"value":1,"type":"double","shape":[1,1]},' ...
    '"E_motor":{"value":0.97,"type":"double","shape":[1,1]},' ...
    '"E_mech":{"value":0.985,"type":"double","shape":[1,1]},' ...
    '"SHAFT":{"value":[0,1,0],"type":"double","shape":[1,3]},' ...
    '"EXT":{"value":[0,0,0],"type":"double","shape":[1,3]},' ...
    '"WA_extraction":{"value":[0,0,0],"type":"double","shape":[1,3]}}'];
custom = component_engine_initialize_configuration(assembly_json, 60, 0, 3000);
assert(isequal(size(custom.F), [1, 3]));
assert(isequal(size(custom.WA_extraction), [1, 3]));
assert(isequal(size(custom.SHAFT), [1, 3]));
report(end+1) = struct('configuration','custom-shape', 'passed',true, ...
    'field_count',numel(fieldnames(custom)));
end
