function [ h ] = SE( T,far )
%根据气体温度、油气比与绝对湿度计算比焓
%Specific Enthalpy
%输入参数
% T     温度
% far   油气比
%输出参数
% h     比焓
A=[-9.75493671e-1,2.50200510e-1,-4.63831922e-5,...
    7.07610366e-08,-9.79460727e-12,-3.17620825e-14,...
    2.400248328e-17,-7.05839430e-21, 7.7411703e-25];
B=[1.69897390e1, 7.38166384e-2, 1.10327671e-3,...
   -1.48736516e-6, 1.45343343e-09,-8.82871343e-13,...
   3.21633291e-16,-6.479651479e-20, 5.5619203e-24];
T_array=T.^linspace(0,8,9);
ha=T_array*A';
hf=T_array*B';
h=(ha + far*hf)/(1.0 + far)*427.0*9.80665;
%湿度修正

end

